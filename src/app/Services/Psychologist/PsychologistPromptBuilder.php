    /**
     * @return array<int, array{role: string, content: string}>
     */
    public function messages(
        PsychologistProfile $profile,
        ?string $summary,
        array $context,
        string $userText,
    ): array {
        $messages = [[
            "role" => "system",
            "content" => $this->systemPrompt($profile, $summary),
        ]];

        foreach ($context as $turn) {
            if (!is_array($turn)) {
                continue;
            }

            $role = $turn["role"] ?? null;
            $content = $turn["content"] ?? null;

            if (
                in_array($role, ["user", "assistant"], true) &&
                is_string($content) &&
                trim($content) !== ""
            ) {
                $messages[] = [
                    "role" => $role,
                    "content" => $content,
                ];
            }
        }

        $messages[] = [
            "role" => "user",
            "content" => $userText,
        ];

        return $messages;
    }

    public function systemPrompt(
        PsychologistProfile $profile,
        ?string $summary,
    ): string {
        $style = match ($profile->style) {
            "direct" => "конкретно, по делу, без лишних метафор",
            "brief" => "очень коротко, 1–3 предложения",
            default => "тепло, бережно, спокойно",
        };

        $summary = is_string($summary) && trim($summary) !== ""
            ? trim($summary)
            : "Пока нет сохранённой памяти. Это начало разговора.";

        return str_replace(
            ["{{memory_summary}}", "{{style}}", "{{preferred_name}}"],
            [
                $summary,
                $style,
                $profile->preferred_name ?: "не указано",
            ],
            self::PROMPT,
        );
    }
}
